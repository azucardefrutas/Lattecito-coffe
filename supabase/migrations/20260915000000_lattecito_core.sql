grant select, insert, update, delete on table public.product_costs to service_role;
grant select, insert, update, delete on table public.admin_sales to service_role;
grant select, insert, update, delete on table public.auth_attempts to service_role;
grant usage, select on sequence public.admin_sales_order_number_seq to service_role;

