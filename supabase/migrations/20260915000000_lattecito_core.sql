begin;

create table if not exists public.catalog_state (
  id smallint primary key check (id = 1),
  catalog jsonb not null,
  version bigint not null default 1,
  updated_at timestamptz not null default now()
);

create table if not exists public.product_costs (
  product_id text primary key,
  costs jsonb not null check (jsonb_typeof(costs) = 'array'),
  updated_at timestamptz not null default now()
);

create table if not exists public.admin_sales (
  id uuid primary key,
  order_number bigint generated by default as identity unique,
  created_at timestamptz not null default now(),
  business_date date not null default ((timezone('America/Cancun', now()))::date),
  created_by text not null,
  confirmed_by text,
  customer text not null default '',
  note text not null default '',
  items jsonb not null check (jsonb_typeof(items) = 'array'),
  subtotal integer not null check (subtotal >= 0),
  total integer not null check (total >= 0),
  cost integer not null check (cost >= 0),
  payment_method text not null check (payment_method in ('Efectivo', 'Transferencia')),
  payment_status text not null check (payment_status in ('Pagado', 'Pendiente')),
  received integer not null check (received >= 0),
  change integer not null check (change >= 0),
  confirmed_at timestamptz
);

create index if not exists admin_sales_business_date_idx
  on public.admin_sales (business_date, created_at desc);

create table if not exists public.auth_attempts (
  attempt_key text primary key,
  attempts integer not null check (attempts >= 0),
  reset_at timestamptz not null
);

alter table public.catalog_state enable row level security;
alter table public.product_costs enable row level security;
alter table public.admin_sales enable row level security;
alter table public.auth_attempts enable row level security;

revoke all on table public.catalog_state from anon, authenticated;
revoke all on table public.product_costs from anon, authenticated;
revoke all on table public.admin_sales from anon, authenticated;
revoke all on table public.auth_attempts from anon, authenticated;

